#!/usr/bin/env python3
"""Turn a PEM bundle of root certificates (Mozilla's, as shipped by certifi or ca-certificates)
into BearSSL trust anchors: include/trust_anchors.h. HTTPS in the kernel checks server
certificates against these.

    python3 tools/gen-trust.py [bundle.pem] [out.h]

Needs the `cryptography` package. Roots with keys BearSSL can't use are skipped."""
import os
import re
import sys

from cryptography import x509
from cryptography.hazmat.primitives.asymmetric import ec, rsa
from cryptography.hazmat.primitives import serialization

KDIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(KDIR, "include", "trust_anchors.h")
CURVES = {"secp256r1": "BR_EC_secp256r1", "secp384r1": "BR_EC_secp384r1", "secp521r1": "BR_EC_secp521r1"}
REJECT = re.compile(r"anthropic|egress|interception|sandbox", re.I)   # never ship a proxy's CA


def default_bundle():
    try:
        import certifi
        return certifi.where()
    except ImportError:
        return "/etc/ssl/certs/ca-certificates.crt"


def carr(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const unsigned char {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main(argv):
    src = argv[0] if argv and argv[0] else default_bundle()
    out = argv[1] if len(argv) > 1 else OUT
    pems = re.findall(rb"-----BEGIN CERTIFICATE-----.+?-----END CERTIFICATE-----", open(src, "rb").read(), re.S)
    arrays, entries, names = [], [], []
    for pem in pems:
        try:
            cert = x509.load_pem_x509_certificate(pem)
        except ValueError:
            continue
        subj = cert.subject.rfc4514_string()
        if REJECT.search(subj):
            continue
        key = cert.public_key()
        i = len(entries)
        dn = cert.subject.public_bytes()
        arrays.append(carr(f"TA{i}_DN", dn))
        if isinstance(key, rsa.RSAPublicKey):
            nums = key.public_numbers()
            n = nums.n.to_bytes((nums.n.bit_length() + 7) // 8, "big")
            e = nums.e.to_bytes((nums.e.bit_length() + 7) // 8, "big")
            arrays.append(carr(f"TA{i}_N", n) + carr(f"TA{i}_E", e))
            k = (f"{{ BR_KEYTYPE_RSA, {{ .rsa = {{ (unsigned char *)TA{i}_N, sizeof TA{i}_N, "
                 f"(unsigned char *)TA{i}_E, sizeof TA{i}_E }} }} }}")
        elif isinstance(key, ec.EllipticCurvePublicKey) and key.curve.name in CURVES:
            q = key.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
            arrays.append(carr(f"TA{i}_Q", q))
            k = f"{{ BR_KEYTYPE_EC, {{ .ec = {{ {CURVES[key.curve.name]}, (unsigned char *)TA{i}_Q, sizeof TA{i}_Q }} }} }}"
        else:
            arrays.pop()
            continue
        entries.append(f"    {{ {{ (unsigned char *)TA{i}_DN, sizeof TA{i}_DN }}, BR_X509_TA_CA, {k} }},")
        names.append(subj)
    text = ("/* Generated by tools/gen-trust.py from Mozilla's root certificates. Do not edit;\n"
            " * run `make trust` to refresh. */\n#ifndef AUXO_TRUST_ANCHORS_H\n#define AUXO_TRUST_ANCHORS_H\n"
            '#include "bearssl.h"\n\n' + "\n".join(arrays) +
            "\nstatic const br_x509_trust_anchor TAs[] = {\n" + "\n".join(entries) + "\n};\n"
            f"#define TAs_NUM {len(entries)}\n\n#endif\n")
    open(out, "w").write(text)
    print(f"{len(entries)} trust anchors → {out}")


if __name__ == "__main__":
    main(sys.argv[1:])
