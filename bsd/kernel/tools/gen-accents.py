#!/usr/bin/env python3
"""Generate include/auxo_accents.h from the Auxo Linux accent palette.

Auxo Linux and AuxoBSD share one palette: packages/auxo-tools/files/lib/auxo_accents.py.
This turns it into a C header so the kernel's auxo-tweak / auxo-fetch use the same
names and colours as the Linux tools.

  tools/gen-accents.py [PALETTE.py] [OUT.h]
  tools/gen-accents.py --check     exit 1 if the committed header is out of date
"""
import ast
import os
import sys

BSD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PALETTE = os.path.join(BSD, "..", "..", "packages", "auxo-tools", "files", "lib", "auxo_accents.py")
OUT = os.path.join(BSD, "include", "auxo_accents.h")


def load(path):
    """Read ACCENTS and DEFAULT without importing (no code from the file is run)."""
    tree = ast.parse(open(path).read(), path)
    vals = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id in ("ACCENTS", "DEFAULT"):
                vals[node.targets[0].id] = ast.literal_eval(node.value)
    return vals["ACCENTS"], vals["DEFAULT"]


def render(accents, default):
    names = list(accents)
    rows = "\n".join(
        f'    {{ "{n}", 0x{a.lstrip("#").lower()}, 0x{b.lstrip("#").lower()} }},' for n, (a, b) in accents.items())
    return f"""/* Generated by tools/gen-accents.py from packages/auxo-tools/files/lib/auxo_accents.py.
 * Do not edit: change the palette there and run `make accents`. */
#ifndef AUXO_ACCENTS_H
#define AUXO_ACCENTS_H
#include <stdint.h>

struct auxo_accent {{
    const char *name;
    uint32_t    c1;     /* primary   0xRRGGBB */
    uint32_t    c2;     /* secondary 0xRRGGBB (gradients) */
}};

static const struct auxo_accent auxo_accents[] = {{
{rows}
}};

#define AUXO_ACCENT_COUNT   {len(names)}
#define AUXO_ACCENT_DEFAULT {names.index(default)}   /* {default} */

#endif
"""


def main(argv):
    check = "--check" in argv
    args = [a for a in argv if a != "--check"]
    src = args[0] if args else PALETTE
    out = args[1] if len(args) > 1 else OUT
    text = render(*load(src))
    if check:
        cur = open(out).read() if os.path.exists(out) else ""
        if cur != text:
            print(f"{out} is out of date: run `make -C bsd/kernel accents`", file=sys.stderr)
            return 1
        print("auxo_accents.h matches the Auxo Linux palette")
        return 0
    with open(out, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
