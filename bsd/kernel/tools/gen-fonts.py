#!/usr/bin/env python3
"""Render the kernel desktop's fonts into include/fonts.h: antialiased 8-bit alpha bitmaps.

  ui      DejaVu Sans 13 px, proportional (titles, panel, apps)
  bold    DejaVu Sans Bold 13 px
  mono    DejaVu Sans Mono in an 8x16 cell (terminal)
  head    DejaVu Sans Bold 21 px, 28 px tall (browser headings, installer titles)

DejaVu fonts: Bitstream Vera licence (free to redistribute, embedded bitmaps included).
Needs Pillow and the DejaVu TTFs (fonts-dejavu-core). The generated header is committed, so
building the kernel doesn't need either.

  tools/gen-fonts.py [OUT.h]
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

KDIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(KDIR, "include", "fonts.h")
FONTDIRS = ["/usr/share/fonts/truetype/dejavu", "/usr/local/share/fonts/dejavu", "/usr/share/fonts/TTF"]

# ASCII plus the symbols the Auxo tools and the desktop draw
EXTRA = "●○▲❯━─█·♥✦✓✗→←↑↓…—–°×▸▾☰⏻"
# web text: Latin-1, typographic punctuation, a few signs pages use a lot
WEB = "".join(chr(c) for c in range(0xA1, 0x100) if chr(c) not in EXTRA) + "‘’‚“”„•‰‹›€™−≈≠≤≥∞″′⋅▶◀■□★☆✔✘⟩⟨"
CHARS = [chr(c) for c in range(32, 127)] + list(EXTRA) + [c for c in WEB if c not in EXTRA]
HEAD_CHARS = [chr(c) for c in range(32, 127)] + [c for c in WEB if c not in EXTRA] + list("…—–·→")
HEIGHT = 16
BASELINE = 12


def find(name):
    for d in FONTDIRS:
        p = os.path.join(d, name)
        if os.path.exists(p):
            return p
    sys.exit(f"gen-fonts: {name} not found (install fonts-dejavu-core)")


def glyph(font, ch, cell_w=None, height=HEIGHT, baseline=BASELINE):
    """→ (advance, width, bitmap bytes [height * width])"""
    adv = round(font.getlength(ch))
    w = cell_w or max(adv, 1)
    img = Image.new("L", (w, height), 0)
    d = ImageDraw.Draw(img)
    asc, _ = font.getmetrics()
    x = 0 if not cell_w else (cell_w - adv) // 2
    d.text((x, baseline - asc), ch, font=font, fill=255)
    return (cell_w or adv), w, img.tobytes()


def has_glyph(font, ch):
    try:
        return font.getmask(ch).getbbox() is not None or ch == " "
    except Exception:
        return False


def emit(name, font, cell_w=None, chars=None, height=HEIGHT, baseline=BASELINE):
    blob, table = bytearray(), []
    fallback = {"❯": ">", "⏻": "o", "☰": "=", "✦": "*"}
    for ch in chars or CHARS:
        src = ch if has_glyph(font, ch) else fallback.get(ch, "?")
        adv, w, bm = glyph(font, src, cell_w, height, baseline)
        table.append((ord(ch), adv, w, len(blob)))
        blob += bm
    lines = [f"static const uint8_t font_{name}_bits[{len(blob)}] = {{"]
    for i in range(0, len(blob), 24):
        lines.append("    " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const struct glyph font_{name}_glyphs[{len(table)}] = {{")
    for cp, adv, w, off in table:
        lines.append(f"    {{ 0x{cp:04x}, {adv}, {w}, {off} }},")
    lines.append("};")
    lines.append(f"const struct font font_{name} = {{ font_{name}_glyphs, {len(table)}, font_{name}_bits, "
                 f"{height}, {baseline} }};")
    return "\n".join(lines)


def main(argv):
    out = argv[0] if argv else OUT
    ui = ImageFont.truetype(find("DejaVuSans.ttf"), 13)
    bold = ImageFont.truetype(find("DejaVuSans-Bold.ttf"), 13)
    mono = ImageFont.truetype(find("DejaVuSansMono.ttf"), 13)
    head = ImageFont.truetype(find("DejaVuSans-Bold.ttf"), 21)
    text = ("/* Generated by tools/gen-fonts.py: DejaVu Sans / Sans Bold / Sans Mono rendered to 8-bit alpha.\n"
            " * DejaVu fonts are under the Bitstream Vera licence. Do not edit; run `make fonts`. */\n"
            "#ifndef AUXO_FONTS_H\n#define AUXO_FONTS_H\n#include <stdint.h>\n\n"
            "struct glyph { uint32_t cp; uint8_t advance, width; uint32_t offset; };\n"
            "struct font { const struct glyph *glyphs; int count; const uint8_t *bits; int height, baseline; };\n\n"
            "extern const struct font font_ui, font_bold, font_mono, font_head;\n\n"
            "#ifdef AUXO_FONTS_IMPL   /* defined by kern/gfx.c only: one copy of the bitmaps */\n"
            + emit("ui", ui) + "\n\n" + emit("bold", bold) + "\n\n" + emit("mono", mono, cell_w=8) + "\n\n"
            + emit("head", head, chars=HEAD_CHARS, height=28, baseline=21) + "\n#endif\n\n#endif\n")
    open(out, "w").write(text)
    print(f"fonts → {out} ({len(CHARS)} glyphs each)")


if __name__ == "__main__":
    main(sys.argv[1:])
