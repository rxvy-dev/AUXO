"""Accent colour engine: one colour, applied everywhere
(GRUB menu, login screen, MOTD, terminals, bars, notifications, KDE/GNOME accents)."""
import os
import shutil

from auxo_accents import ACCENTS, DEFAULT, hex_to_rgb
from auxo_core import (R, DRY, log, run, have, read_conf, write_conf, write_file, set_kv,
                       home_of, chown)
from auxo_desktops import GNOME_ACCENT

WALLDIR = "/usr/share/wallpapers"
GRUB_THEME = "/usr/share/grub/themes/auxo"


def current():
    a = read_conf().get("ACCENT", DEFAULT)
    return a if a in ACCENTS else DEFAULT


def colors(accent):
    a, b = ACCENTS[accent]
    return {"accent": a, "accent2": b, "bg": "#0b0b10", "bg2": "#15151e", "fg": "#e8e8f0",
            "muted": "#6b6b80", "urgent": "#fb7185"}


