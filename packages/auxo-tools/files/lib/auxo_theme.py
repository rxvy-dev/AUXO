def _solid_png(path, rgb):
    """Write a tiny solid-colour PNG without Pillow (used for GRUB selection pixmaps)."""
    import struct
    import zlib
    w = h = 4
    raw = b"".join(b"\x00" + bytes(rgb) * w for _ in range(h))

    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    data = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) + \
        chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(data)


def apply_grub(accent, mkconfig=True):
    c = colors(accent)
    d = R(GRUB_THEME)
    os.makedirs(d, exist_ok=True)
    wall = R(f"{WALLDIR}/auxo-{accent}.png")
    if os.path.exists(wall):
        shutil.copyfile(wall, os.path.join(d, "background.png"))
    write_file(f"{GRUB_THEME}/theme.txt", grub_theme_txt(c))
    for part in ("c", "n", "s", "e", "w", "ne", "nw", "se", "sw"):
        _solid_png(os.path.join(d, f"select_{part}.png"), hex_to_rgb(c["accent"]))
    if os.path.exists(R("/etc/default/grub")):
        set_kv("/etc/default/grub", "GRUB_THEME", f"{GRUB_THEME}/theme.txt")
        set_kv("/etc/default/grub", "GRUB_GFXMODE", "auto")
        set_kv("/etc/default/grub", "GRUB_TERMINAL_OUTPUT", "gfxterm")
        set_kv("/etc/default/grub", "GRUB_DISTRIBUTOR", "Auxo")
        # GRUB reads theme.txt + background.png at every boot, so an accent change only
        # needs a grub.cfg rebuild the first time the Auxo theme is wired in.
        cfg = R("/boot/grub/grub.cfg")
        wired = os.path.exists(cfg) and f"{GRUB_THEME}/theme.txt" in open(cfg, errors="ignore").read()
        if mkconfig and not wired and have("grub-mkconfig") and os.path.exists(R("/boot/grub")):
            grub_mkconfig()


def grub_mkconfig():
    """Rebuild grub.cfg safely: one run at a time (grub-btrfsd can start its own),
    with a single retry if another run removed grub.cfg.new underneath us."""
    cmd = ["flock", "-w", "120", "/run/lock/auxo-grub.lock", "grub-mkconfig", "-o", "/boot/grub/grub.cfg"]
    if run(cmd, check=False) != 0:
        import time
        time.sleep(3)
        if run(cmd, check=False) != 0:
            log("grub-mkconfig failed — your old boot menu is untouched; run 'sudo grub-mkconfig -o /boot/grub/grub.cfg' to see why")
            return False
    return True


# nearest terminal colour for each accent (tuigreet draws with the 16 ANSI colours)
TUI_COLOR = {"violet": "magenta", "cyan": "cyan", "emerald": "green", "amber": "yellow",
             "rose": "red", "blue": "blue", "mono": "white"}


def greetd_config(accent, cmd=None):
    c = TUI_COLOR.get(accent, "magenta")
    theme = f"border={c};title={c};greet=white;prompt={c};input=white;action={c};button={c};time=darkgray;text=gray"
    args = ["tuigreet", "--time", "--remember", "--remember-user-session",
            "--greeting 'Auxo Linux — climb your own setup'", f"--theme '{theme}'",
            "--sessions /usr/share/wayland-sessions", "--xsessions /usr/share/xsessions",
            "--xsession-wrapper 'startx /usr/bin/env'"]
    if cmd:
        args.append(f"--cmd '{cmd}'")
    command = " ".join(args).replace('"', '\\"')
    return ("# written by auxo-tweak — text login (greetd + tuigreet)\n"
            # vt 7: Void runs agetty (text logins) on tty1-6. Sharing tty1 with it split every
            # keystroke between the two, so passwords typed at the login screen came out wrong.
            "[terminal]\nvt = 7\n\n"
            f'[default_session]\ncommand = "{command}"\nuser = "_greeter"\n')


def apply_login(accent):
    """Text login screen (greetd + tuigreet) in the accent colour, starting the chosen desktop."""
    if not (os.path.isdir(R("/etc/greetd")) or os.path.exists(R("/usr/bin/tuigreet"))):
        return
    from auxo_desktops import DESKTOPS
    d = DESKTOPS.get(read_conf().get("DESKTOP", ""), {})
    write_file("/etc/greetd/config.toml", greetd_config(accent, d.get("cmd")))


def apply_sddm(accent):
    """Only used by the live ISO now (installed systems use greetd).
    Never point SDDM at a theme that isn't really installed: a Breeze folder without
    metadata.desktop makes SDDM try a greeter that isn't installed → black screen."""
    if not os.path.exists(R("/usr/bin/sddm")):
        return
    wall = f"{WALLDIR}/auxo-{accent}.png"
    if os.path.exists(R("/usr/bin/kwin_wayland")):
        server = ("[General]\nDisplayServer=wayland\nGreeterEnvironment=QT_WAYLAND_SHELL_INTEGRATION=layer-shell\nInputMethod=\n\n"
                  "[Wayland]\nCompositorCommand=kwin_wayland --drm --no-lockscreen --no-global-shortcuts --locale1\n\n")
    else:
        server = "[General]\nDisplayServer=x11\nInputMethod=\n\n"
    breeze = R("/usr/share/sddm/themes/breeze/metadata.desktop")
    theme = "[Theme]\nCurrent=breeze\nCursorTheme=breeze_cursors\n" if os.path.exists(breeze) else "[Theme]\nCurrent=\n"
    write_file("/etc/sddm.conf.d/10-auxo.conf", server + theme)
    if os.path.exists(breeze):
        write_file("/usr/share/sddm/themes/breeze/theme.conf.user", f"[General]\nbackground={wall}\ntype=image\n")


def motd(accent):
    r, g, b = hex_to_rgb(ACCENTS[accent][0])
    r2, g2, b2 = hex_to_rgb(ACCENTS[accent][1])
    c1, c2, rs = f"\033[38;2;{r};{g};{b}m", f"\033[38;2;{r2};{g2};{b2}m", "\033[0m"
    return (f"\n{c1}      /\\       {rs}\033[1mAuxo Linux{rs}  —  climb your own setup\n"
            f"{c1}     /  \\      {rs}  auxo-tweak   change accent, kernel, desktop, shell\n"
            f"{c2}    / /\\ \\     {rs}  auxo-update  snapshot + update everything\n"
            f"{c2}   /_/  \\_\\    {rs}  auxo-fetch   system summary\n\n")


def apply_system(accent, mkconfig=True):
    if accent not in ACCENTS:
        raise ValueError(f"unknown accent '{accent}'. choose: {', '.join(ACCENTS)}")
    write_conf({"ACCENT": accent})
    apply_grub(accent, mkconfig)
    apply_sddm(accent)
    apply_login(accent)
    write_file("/etc/motd", motd(accent))
    import auxo_kde
    auxo_kde.apply_system(accent)
    log(f"system accent → {accent} ({ACCENTS[accent][0]})")


