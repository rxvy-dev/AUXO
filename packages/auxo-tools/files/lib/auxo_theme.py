def mako_config(accent, look=None):
    look = look or auxo_look.DEFAULTS
    c = colors(accent, look["mode"])
    size = int(look["font_size"]) + 1
    return (f"# generated by auxo-tweak\nfont={look['ui_font']} {size}\nbackground-color={c['bg2']}ee\ntext-color={c['fg']}\n"
            f"border-color={c['accent']}\nborder-size=2\nborder-radius={min(int(look['rounding']), 16)}\npadding=12\nwidth=360\ndefault-timeout=6000\n"
            f"[urgency=high]\nborder-color={c['urgent']}\n")


def apply_user(user, accent, autostart=True, desktop=None):
    home = home_of(user)
    cfg = f"{home}/.config/auxo"
    look = auxo_look.load(home)
    for name, content in user_color_files(accent, look["mode"]).items():
        write_file(f"{cfg}/{name}", content)
    # the rices point at ~/.config/auxo/wallpaper.png: your own image, or the Auxo one in your accent
    link = R(f"{cfg}/wallpaper.png")
    if os.path.lexists(link):
        os.remove(link)
    os.symlink(auxo_look.wallpaper(look, accent), link)
    # gaps, corners, fonts, transparency, bar position … for every desktop that reads files
    auxo_look.write_user(home, look, accent, desktop or read_conf().get("DESKTOP"))
    if os.path.isdir(R(f"{home}/.config/mako")):
        write_file(f"{home}/.config/mako/config", mako_config(accent, look))
    if os.path.isdir(R(f"{home}/.config/dunst")):
        os.makedirs(R(f"{home}/.config/dunst/dunstrc.d"), exist_ok=True)
        shutil.copyfile(R(f"{cfg}/dunst.conf"), R(f"{home}/.config/dunst/dunstrc.d/50-auxo.conf"))
    # KDE: Auxo global theme + colours with this accent (right from the first login)
    import auxo_kde
    auxo_kde.merge_kdeglobals(f"{home}/.config/kdeglobals", accent, look)
    # one-shot autostart that pushes wallpaper/accent (and the GNOME/Cinnamon/Xfce rice) into
    # whatever desktop starts next
    if autostart:
        write_file(f"{home}/.config/autostart/auxo-session-apply.desktop",
                   "[Desktop Entry]\nType=Application\nName=Auxo accent\nExec=auxo-tweak session-apply --once\n"
               "NoDisplay=true\nX-GNOME-Autostart-enabled=true\n")
    chown(f"{home}/.config", user, recursive=True)
    log(f"{user}: accent → {accent}")


def _ini_set(path, section, key, value):
    lines = open(path).read().splitlines() if os.path.exists(path) else []
    out, in_sec, done, found_sec = [], False, False, False
    for line in lines:
        s = line.strip()
        if s.startswith("[") and s.endswith("]"):
            if in_sec and not done:
                out.append(f"{key}={value}")
                done = True
            in_sec = s[1:-1] == section
            found_sec = found_sec or in_sec
        elif in_sec and s.split("=", 1)[0] == key:
            if not done:
                out.append(f"{key}={value}")
                done = True
            continue
        out.append(line)
    if not found_sec:
        out += ["", f"[{section}]"]
    if not done:
        out.append(f"{key}={value}")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(out).lstrip("\n") + "\n")


# process name → XDG_CURRENT_DESKTOP, in detection order
SESSION_PROCS = [("plasmashell", "KDE"), ("gnome-shell", "GNOME"), ("cinnamon", "X-Cinnamon"),
                 ("xfce4-session", "XFCE"), ("Hyprland", "Hyprland"), ("sway", "sway"), ("i3", "i3"),
                 ("chrono", "Chrono")]


def session_env(user):
    """Environment for talking to `user`'s running graphical session (or None).
    Built from /run/user/<uid> and the running processes, because sudo strips
    DISPLAY / WAYLAND_DISPLAY / DBUS_SESSION_BUS_ADDRESS."""
    import glob
    import pwd
    if DRY:
        return None
    try:
        pw = pwd.getpwnam(user)
    except KeyError:
        return None
    rt = f"/run/user/{pw.pw_uid}"
    if not os.path.isdir(rt):
        return None
    procs = set((run(["ps", "-u", str(pw.pw_uid), "-o", "comm="], capture=True, check=False) or "").split())
    desk = next((d for p, d in SESSION_PROCS if p in procs), None)
    if not desk:
        return None
    env = {"XDG_RUNTIME_DIR": rt, "HOME": pw.pw_dir, "USER": user, "LOGNAME": user,
           "XDG_CURRENT_DESKTOP": desk}
    if os.path.exists(f"{rt}/bus"):
        env["DBUS_SESSION_BUS_ADDRESS"] = f"unix:path={rt}/bus"
    way = sorted(p for p in glob.glob(f"{rt}/wayland-*") if not p.endswith(".lock"))
    if way:
        env["WAYLAND_DISPLAY"] = os.path.basename(way[0])
    xs = sorted(glob.glob("/tmp/.X11-unix/X*"))
    if xs:
        env["DISPLAY"] = ":" + xs[0].rsplit("X", 1)[1]
        xa = os.path.join(pw.pw_dir, ".Xauthority")
        if os.path.exists(xa):
            env["XAUTHORITY"] = xa
    hy = sorted(glob.glob(f"{rt}/hypr/*/.socket.sock"), key=os.path.getmtime)
    if hy:
        env["HYPRLAND_INSTANCE_SIGNATURE"] = os.path.basename(os.path.dirname(hy[-1]))
    sw = sorted(glob.glob(f"{rt}/sway-ipc.*.sock"), key=os.path.getmtime)
    if sw:
        env["SWAYSOCK"] = sw[-1]
    # the session's own environment is the truth: on Void desktops start under dbus-run-session,
    # so the session bus has a random address that /run/user/<uid>/bus doesn't point to
    env.update(_session_proc_env(pw.pw_uid, {p for p, d in SESSION_PROCS if d == desk}))
    return env


SESSION_KEYS = ("DBUS_SESSION_BUS_ADDRESS", "WAYLAND_DISPLAY", "DISPLAY", "XAUTHORITY", "HYPRLAND_INSTANCE_SIGNATURE",
                "SWAYSOCK", "XDG_CURRENT_DESKTOP", "XDG_SESSION_TYPE")


def _session_proc_env(uid, names, proc="/proc"):
    """SESSION_KEYS from the environment of the user's running compositor/shell (readable by
    root and by the user themselves)."""
    for pid in sorted((d for d in os.listdir(proc) if d.isdigit()), key=int, reverse=True):
        try:
            if os.stat(f"{proc}/{pid}").st_uid != uid:
                continue
            with open(f"{proc}/{pid}/comm") as f:
                if f.read().strip() not in names:
                    continue
            with open(f"{proc}/{pid}/environ", "rb") as f:
                raw = f.read().split(b"\0")
        except OSError:
            continue
        found = {}
        for item in raw:
            k, _, v = item.decode(errors="replace").partition("=")
            if k in SESSION_KEYS and v:
                found[k] = v
        if found:
            return found
    return {}


def _spawn(cmd):
    """Start a long-running helper (wallpaper daemon) detached from us."""
    import subprocess
    if DRY:
        print("[dry-run] " + " ".join(cmd) + " &", flush=True)
        return
    try:
        subprocess.Popen(cmd, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                         start_new_session=True)
    except OSError:
        pass


def _gs(schema, key, value):
    """gsettings set, quietly (a key missing on this version must not stop the rest)."""
    run(["gsettings", "set", schema, key, value], check=False)


def _q(s):
    return "'" + s.replace("'", "\\'") + "'"


def _icons(dark):
    name = "Papirus-Dark" if dark else "Papirus-Light"
    return name if os.path.isdir(R(f"/usr/share/icons/{name}")) or DRY else None


def _gnome_terminal_key(cmd):
    """Super+Return opens a terminal: added to GNOME's custom shortcuts, keeping the user's own."""
    base = "org.gnome.settings-daemon.plugins.media-keys"
    path = "/org/gnome/settings-daemon/plugins/media-keys/custom-keybindings/auxo-terminal/"
    cur = (run(["gsettings", "get", base, "custom-keybindings"], capture=True, check=False) or "").strip()
    paths = re.findall(r"'([^']+)'", cur)
    if path not in paths:
        paths.append(path)
        _gs(base, "custom-keybindings", "[" + ", ".join(_q(p) for p in paths) + "]")
    sch = f"{base}.custom-keybinding:{path}"
    _gs(sch, "name", "'Terminal'")
    _gs(sch, "command", _q(cmd))
    _gs(sch, "binding", "'<Super>Return'")


def _gnome(look, accent, wall, rice):
    dark = look["mode"] == "dark"
    ui, mono, size = look["ui_font"], look["mono_font"], look["font_size"]
    i = "org.gnome.desktop.interface"
    for key in ("picture-uri", "picture-uri-dark"):
        _gs("org.gnome.desktop.background", key, f"file://{wall}")
    _gs("org.gnome.desktop.background", "picture-options", "zoom")
    _gs("org.gnome.desktop.screensaver", "picture-uri", f"file://{wall}")
    _gs(i, "color-scheme", "prefer-dark" if dark else "default")
    _gs(i, "gtk-theme", "Adwaita-dark" if dark else "Adwaita")      # older GTK 3 apps follow too
    _gs(i, "accent-color", GNOME_ACCENT[accent])
    _gs(i, "font-name", f"{ui} {size}")
    _gs(i, "document-font-name", f"{ui} {int(size) + 1}")
    _gs(i, "monospace-font-name", f"{mono} {size}")
    _gs("org.gnome.desktop.wm.preferences", "titlebar-font", f"{ui} Bold {size}")
    _gs(i, "enable-animations", "true" if auxo_look.on(look, "animations") else "false")
    icons = _icons(dark)
    if icons:
        _gs(i, "icon-theme", icons)
    if rice:
        # the Auxo GNOME rice: GNOME's own settings only — no extensions (an extension-based
        # rice in Auxo 3.0.4 stopped the GNOME session from starting)
        _gs("org.gnome.desktop.wm.preferences", "button-layout", "appmenu:minimize,maximize,close")
        _gs(i, "clock-show-weekday", "true")
        _gs(i, "show-battery-percentage", "true")
        _gs("org.gnome.desktop.peripherals.touchpad", "tap-to-click", "true")
        _gs("org.gnome.mutter", "center-new-windows", "true")
        _gnome_terminal_key("kgx")


def _cinnamon(look, wall, rice):
    dark = look["mode"] == "dark"
    ui, mono, size = look["ui_font"], look["mono_font"], look["font_size"]
    i = "org.cinnamon.desktop.interface"
    _gs("org.cinnamon.desktop.background", "picture-uri", f"file://{wall}")
    _gs("org.cinnamon.desktop.background", "picture-options", "zoom")
    _gs(i, "gtk-theme", "Adwaita-dark" if dark else "Adwaita")
    _gs(i, "font-name", f"{ui} {size}")
    _gs("org.gnome.desktop.interface", "monospace-font-name", f"{mono} {size}")
    _gs("org.cinnamon.desktop.wm.preferences", "titlebar-font", f"{ui} Bold {size}")
    _gs(i, "enable-animations", "true" if auxo_look.on(look, "animations") else "false")
    _gs("org.cinnamon", "desktop-effects", "true" if auxo_look.on(look, "animations") else "false")
    icons = _icons(dark)
    if icons:
        _gs(i, "icon-theme", icons)
    # move the main panel (a single "1:0:…" panel); someone's multi-panel layout is left alone
    cur = run(["gsettings", "get", "org.cinnamon", "panels-enabled"], capture=True, check=False) or ""
    if DRY or re.fullmatch(r"\s*\['1:0:(top|bottom)'\]\s*", cur):
        _gs("org.cinnamon", "panels-enabled", f"['1:0:{look['bar']}']")
    if rice:
        _gs("org.cinnamon.desktop.wm.preferences", "button-layout", ":minimize,maximize,close")
        _gs("org.cinnamon", "panels-height", "['1:40']")


def _xfconf(channel, prop, kind, value):
    run(["xfconf-query", "-c", channel, "-p", prop, "--create", "-t", kind, "-s", value], check=False)


def _xfce(look, wall, rice):
    dark = look["mode"] == "dark"
    ui, mono, size = look["ui_font"], look["mono_font"], look["font_size"]
    props = [p for p in (run(["xfconf-query", "-c", "xfce4-desktop", "-l"], capture=True, check=False) or "").split()
             if p.endswith("/last-image")]
    for p in props or ["/backdrop/screen0/monitor0/workspace0/last-image"]:
        _xfconf("xfce4-desktop", p, "string", wall)
    _xfconf("xsettings", "/Net/ThemeName", "string", "Adwaita-dark" if dark else "Adwaita")
    icons = _icons(dark)
    if icons:
        _xfconf("xsettings", "/Net/IconThemeName", "string", icons)
    _xfconf("xsettings", "/Gtk/FontName", "string", f"{ui} {size}")
    _xfconf("xsettings", "/Gtk/MonospaceFontName", "string", f"{mono} {size}")
    _xfconf("xfwm4", "/general/title_font", "string", f"{ui} Bold {size}")
    _xfconf("xfwm4", "/general/use_compositing", "bool", "true")
    _xfconf("xfwm4", "/general/inactive_opacity", "int", "92" if auxo_look.on(look, "transparency") else "100")
    _xfconf("xfce4-panel", "/panels/dark-mode", "bool", "true" if dark else "false")
    # panel-1 is the main panel: p=6 = top edge (Xfce's default), p=8 = bottom edge, full width
    _xfconf("xfce4-panel", "/panels/panel-1/position", "string", "p=6;x=0;y=0" if look["bar"] == "top" else "p=8;x=0;y=0")
    if rice:
        _xfconf("xfwm4", "/general/button_layout", "string", "O|HMC")
        _xfconf("xfwm4", "/general/show_frame_shadow", "bool", "true")
        _xfconf("xfce4-panel", "/panels/panel-1/size", "uint", "32")
        _xfconf("xfce4-panel", "/panels/panel-1/icon-size", "uint", "18")
    if have("xfce4-panel"):
        run(["xfce4-panel", "-r"], check=False)


def _kde(look, accent, wall):
    a = ACCENTS[accent][0] if look["mode"] == "dark" else auxo_look.LIGHT_ACCENT[accent][0]
    if have("plasma-apply-colorscheme"):
        light = look["mode"] == "light"
        name = "AuxoLight" if light else "AuxoDark"
        exists = os.path.exists(f"/usr/share/color-schemes/{name}.colors") or DRY
        run(["plasma-apply-colorscheme", "--accent-color", a, name if exists else ("BreezeLight" if light else "BreezeDark")],
            check=False)
    if have("plasma-apply-wallpaperimage"):
        run(["plasma-apply-wallpaperimage", wall], check=False)
    # panel position, live
    js = f"panels().forEach(function (p) {{ p.location = '{look['bar']}'; }})"
    run(["dbus-send", "--session", "--type=method_call", "--dest=org.kde.plasmashell", "/PlasmaShell",
         "org.kde.PlasmaShell.evaluateScript", f"string:{js}"], check=False)
    run(["dbus-send", "--session", "--type=method_call", "--dest=org.kde.KWin", "/KWin", "org.kde.KWin.reconfigure"],
        check=False)


def _restart_bar(launcher):
    """Waybar reads its position only at start: restart it inside the session."""
    run(["pkill", "-x", "waybar"], check=False)
    if have("waybar"):
        if run(launcher + ["waybar"], check=False) != 0:
            _spawn(["waybar"])


def session_apply(accent=None, once=False, rice=False):
    """Run inside a graphical session: push accent, wallpaper and look settings to the live desktop.
    rice=True also applies the Auxo rice for GNOME / Cinnamon / Xfce (first login, `auxo-tweak rice`)."""
    import pwd
    accent = accent or current()
    try:
        me = pwd.getpwuid(os.getuid()).pw_name
    except KeyError:
        me = os.environ.get("USER", "root")
    home = os.environ.get("AUXO_HOME") or home_of(me)
    look = auxo_look.load(home)
    wall = auxo_look.wallpaper(look, accent)
    rice = rice or once
    de = os.environ.get("XDG_CURRENT_DESKTOP", "").lower()
    if "kde" in de:
        _kde(look, accent, wall)
    elif "gnome" in de and have("gsettings"):
        _gnome(look, accent, wall, rice)
    elif "cinnamon" in de and have("gsettings"):
        _cinnamon(look, wall, rice)
    elif "xfce" in de and have("xfconf-query"):
        _xfce(look, wall, rice)
    elif "hyprland" in de:
        # hyprpaper keeps the old image in memory: restart it on the new wallpaper
        run(["pkill", "-x", "hyprpaper"], check=False)
        # let Hyprland start it (so it lives in the session); detach it ourselves as a fallback
        if have("hyprpaper") and not (have("hyprctl") and run(["hyprctl", "dispatch", "exec", "hyprpaper"], check=False) == 0):
            _spawn(["hyprpaper"])
        if have("hyprctl"):
            run(["hyprctl", "reload"], check=False)
        _restart_bar(["hyprctl", "dispatch", "exec"])
        run(["makoctl", "reload"], check=False)
    elif "sway" in de and have("swaymsg"):
        run(["swaymsg", "reload"], check=False)
        run(["swaymsg", "output", "*", "bg", wall, "fill"], check=False)
        _restart_bar(["swaymsg", "exec"])
        run(["makoctl", "reload"], check=False)
    elif "i3" in de:
        if have("feh"):
            run(["feh", "--no-fehbg", "--bg-fill", wall], check=False)
        run(["pkill", "-x", "picom"], check=False)
        if have("i3-msg"):
            run(["i3-msg", "exec", "picom -b"], check=False)
            run(["i3-msg", "restart"], check=False)     # re-runs the polybar launcher too
    elif "chrono" in de:
        if have("chronoctl"):
            run(["chronoctl", "reload"], check=False)
    if once:
        p = os.path.expanduser("~/.config/autostart/auxo-session-apply.desktop")
        if os.path.exists(p) and not DRY:
            os.remove(p)
