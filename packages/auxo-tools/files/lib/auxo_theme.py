def _solid_png(path, rgb):
    """Write a tiny solid-colour PNG without Pillow (used for GRUB selection pixmaps)."""
    import struct
    import zlib
    w = h = 4
    raw = b"".join(b"\x00" + bytes(rgb) * w for _ in range(h))

    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    data = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) + \
        chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(data)


def apply_grub(accent, mkconfig=True):
    c = colors(accent)
    d = R(GRUB_THEME)
    os.makedirs(d, exist_ok=True)
    wall = R(f"{WALLDIR}/auxo-{accent}.png")
    if os.path.exists(wall):
        shutil.copyfile(wall, os.path.join(d, "background.png"))
    write_file(f"{GRUB_THEME}/theme.txt", grub_theme_txt(c))
    for part in ("c", "n", "s", "e", "w", "ne", "nw", "se", "sw"):
        _solid_png(os.path.join(d, f"select_{part}.png"), hex_to_rgb(c["accent"]))
    if os.path.exists(R("/etc/default/grub")):
        set_kv("/etc/default/grub", "GRUB_THEME", f"{GRUB_THEME}/theme.txt")
        set_kv("/etc/default/grub", "GRUB_GFXMODE", "auto")
        set_kv("/etc/default/grub", "GRUB_TERMINAL_OUTPUT", "gfxterm")
        set_kv("/etc/default/grub", "GRUB_DISTRIBUTOR", "Auxo")
        if mkconfig and have("grub-mkconfig") and os.path.exists(R("/boot/grub")):
            run(["grub-mkconfig", "-o", "/boot/grub/grub.cfg"], check=False)


def apply_sddm(accent):
    wall = f"{WALLDIR}/auxo-{accent}.png"
    if os.path.exists(R("/usr/bin/kwin_wayland")):
        # Plasma present: Wayland greeter running on KWin
        server = ("[General]\nDisplayServer=wayland\nGreeterEnvironment=QT_WAYLAND_SHELL_INTEGRATION=layer-shell\nInputMethod=\n\n"
                  "[Wayland]\nCompositorCommand=kwin_wayland --drm --no-lockscreen --no-global-shortcuts --locale1\n\n")
    else:
        server = "[General]\nDisplayServer=x11\nInputMethod=\n\n"
    write_file("/etc/sddm.conf.d/10-auxo.conf", server + "[Theme]\nCurrent=breeze\nCursorTheme=breeze_cursors\n")
    if os.path.isdir(R("/usr/share/sddm/themes/breeze")):
        write_file("/usr/share/sddm/themes/breeze/theme.conf.user", f"[General]\nbackground={wall}\ntype=image\n")


def motd(accent):
    r, g, b = hex_to_rgb(ACCENTS[accent][0])
    r2, g2, b2 = hex_to_rgb(ACCENTS[accent][1])
    c1, c2, rs = f"\033[38;2;{r};{g};{b}m", f"\033[38;2;{r2};{g2};{b2}m", "\033[0m"
    return (f"\n{c1}      /\\       {rs}\033[1mAuxo Linux{rs}  —  climb your own setup\n"
            f"{c1}     /  \\      {rs}  auxo-tweak   change accent, kernel, desktop, shell\n"
            f"{c2}    / /\\ \\     {rs}  auxo-update  snapshot + update everything\n"
            f"{c2}   /_/  \\_\\    {rs}  auxo-fetch   system summary\n\n")


def apply_system(accent, mkconfig=True):
    if accent not in ACCENTS:
        raise ValueError(f"unknown accent '{accent}'. choose: {', '.join(ACCENTS)}")
    write_conf({"ACCENT": accent})
    apply_grub(accent, mkconfig)
    apply_sddm(accent)
    write_file("/etc/motd", motd(accent))
    log(f"system accent → {accent} ({ACCENTS[accent][0]})")


# ── per-user ──────────────────────────────────────────────────────────
