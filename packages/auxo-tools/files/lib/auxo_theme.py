def mako_config(accent):
    c = colors(accent)
    return (f"# generated by auxo-tweak\nfont=Inter 11\nbackground-color={c['bg2']}ee\ntext-color={c['fg']}\n"
            f"border-color={c['accent']}\nborder-size=2\nborder-radius=10\npadding=12\nwidth=360\ndefault-timeout=6000\n"
            f"[urgency=high]\nborder-color={c['urgent']}\n")


def apply_user(user, accent):
    home = home_of(user)
    cfg = f"{home}/.config/auxo"
    for name, content in user_color_files(accent).items():
        write_file(f"{cfg}/{name}", content)
    # the rices point at ~/.config/auxo/wallpaper.png
    link = R(f"{cfg}/wallpaper.png")
    if os.path.lexists(link):
        os.remove(link)
    os.symlink(f"{WALLDIR}/auxo-{accent}.png", link)
    if os.path.isdir(R(f"{home}/.config/mako")):
        write_file(f"{home}/.config/mako/config", mako_config(accent))
    if os.path.isdir(R(f"{home}/.config/dunst")):
        os.makedirs(R(f"{home}/.config/dunst/dunstrc.d"), exist_ok=True)
        shutil.copyfile(R(f"{cfg}/dunst.conf"), R(f"{home}/.config/dunst/dunstrc.d/50-auxo.conf"))
    # KDE: accent + dark scheme are picked up at next login
    r, g, b = hex_to_rgb(ACCENTS[accent][0])
    kg = R(f"{home}/.config/kdeglobals")
    _ini_set(kg, "General", "AccentColor", f"{r},{g},{b}")
    _ini_set(kg, "General", "ColorScheme", "BreezeDark")
    _ini_set(kg, "KDE", "LookAndFeelPackage", "org.kde.breezedark.desktop")
    # one-shot autostart that pushes wallpaper/accent into whatever desktop starts next
    write_file(f"{home}/.config/autostart/auxo-session-apply.desktop",
               "[Desktop Entry]\nType=Application\nName=Auxo accent\nExec=auxo-tweak session-apply --once\n"
               "NoDisplay=true\nX-GNOME-Autostart-enabled=true\n")
    chown(f"{home}/.config", user, recursive=True)
    log(f"{user}: accent → {accent}")


def _ini_set(path, section, key, value):
    lines = open(path).read().splitlines() if os.path.exists(path) else []
    out, in_sec, done, found_sec = [], False, False, False
    for line in lines:
        s = line.strip()
        if s.startswith("[") and s.endswith("]"):
            if in_sec and not done:
                out.append(f"{key}={value}")
                done = True
            in_sec = s[1:-1] == section
            found_sec = found_sec or in_sec
        elif in_sec and s.split("=", 1)[0] == key:
            if not done:
                out.append(f"{key}={value}")
                done = True
            continue
        out.append(line)
    if not found_sec:
        out += ["", f"[{section}]"]
    if not done:
        out.append(f"{key}={value}")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(out).lstrip("\n") + "\n")


def session_apply(accent=None, once=False):
    """Run inside a graphical session: push accent + wallpaper to the live desktop."""
    accent = accent or current()
    wall = f"{WALLDIR}/auxo-{accent}.png"
    a = ACCENTS[accent][0]
    de = os.environ.get("XDG_CURRENT_DESKTOP", "").lower()
    if "kde" in de and have("plasma-apply-colorscheme"):
        run(["plasma-apply-colorscheme", "--accent-color", a, "BreezeDark"], check=False)
        run(["plasma-apply-wallpaperimage", wall], check=False)
    elif "gnome" in de and have("gsettings"):
        for key in ("picture-uri", "picture-uri-dark"):
            run(["gsettings", "set", "org.gnome.desktop.background", key, f"file://{wall}"], check=False)
        run(["gsettings", "set", "org.gnome.desktop.interface", "color-scheme", "prefer-dark"], check=False)
        run(["gsettings", "set", "org.gnome.desktop.interface", "accent-color", GNOME_ACCENT[accent]], check=False)
    elif "cinnamon" in de and have("gsettings"):
        run(["gsettings", "set", "org.cinnamon.desktop.background", "picture-uri", f"file://{wall}"], check=False)
    elif "xfce" in de and have("xfconf-query"):
        props = run(["xfconf-query", "-c", "xfce4-desktop", "-l"], capture=True, check=False) or ""
        for p in props.split():
            if p.endswith("/last-image"):
                run(["xfconf-query", "-c", "xfce4-desktop", "-p", p, "-s", wall], check=False)
    elif "hyprland" in de and have("hyprctl"):
        run(["hyprctl", "reload"], check=False)
        run(["pkill", "-SIGUSR2", "waybar"], check=False)
        run(["makoctl", "reload"], check=False)
    elif "sway" in de and have("swaymsg"):
        run(["swaymsg", "reload"], check=False)
        run(["makoctl", "reload"], check=False)
    elif "i3" in de and have("i3-msg"):
        run(["i3-msg", "restart"], check=False)
    if once:
        p = os.path.expanduser("~/.config/autostart/auxo-session-apply.desktop")
        if os.path.exists(p) and not DRY:
            os.remove(p)
